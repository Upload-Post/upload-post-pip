"""The client covers the whole API.

Every operation of codegen/openapi.json has a method (hand-written ones are
listed in codegen/sdk-map.json, the rest are generated by codegen/generate.py),
and calling that method sends the HTTP method and path the spec describes. A
new operation in the spec fails here until it has a method: run
``python3 codegen/generate.py``.

No network: the session is patched, so every assertion is about what the
client would have sent.

Run with: python -m unittest discover -s tests
"""

import inspect
import json
import os
import re
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import MagicMock, patch

import requests

from upload_post import UploadPostClient, UploadPostError

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = "https://api.upload-post.com/api"

with open(os.path.join(ROOT, "codegen", "openapi.json"), encoding="utf-8") as fh:
    SPEC = json.load(fh)
with open(os.path.join(ROOT, "codegen", "sdk-map.json"), encoding="utf-8") as fh:
    MAP = json.load(fh)
TABLE = UploadPostClient._OPENAPI_OPERATIONS


def resolve(node):
    while isinstance(node, dict) and "$ref" in node:
        target = SPEC
        for part in node["$ref"][2:].split("/"):
            target = target[part]
        node = target
    return node or {}


def spec_operations():
    ops = []
    for route, item in SPEC["paths"].items():
        for verb in ("get", "post", "put", "patch", "delete"):
            op = item.get(verb)
            if not op:
                continue
            params = [resolve(p) for p in item.get("parameters", []) + op.get("parameters", [])]
            required = [p["name"] for p in params if p.get("in") != "header" and p.get("required")]
            for content in op.get("requestBody", {}).get("content", {}).values():
                required += [n for n in resolve(content.get("schema")).get("required", []) if n not in required]
            ops.append({"id": op["operationId"], "verb": verb.upper(), "route": route, "required": required})
    return ops


OPS = spec_operations()


def method_for(op):
    if op["id"] in MAP["existing"]:
        return MAP["existing"][op["id"]]
    if op["id"] in TABLE:
        return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", MAP.get("names", {}).get(op["id"]) or _js_name(op["id"])).lower()
    return None


def _js_name(op_id):
    for a, b in (("LinkedIn", "Linkedin"), ("AutoDM", "Autodm"), ("OAuth", "Oauth"),
                 ("WordPress", "Wordpress"), ("DevTo", "Devto"), ("YouTube", "Youtube")):
        op_id = op_id.replace(a, b)
    return op_id


def route_regex(route):
    route = re.escape(route.rstrip("/"))
    return re.compile("^" + re.sub(r"\\\{\w+\\\}", "[^/]+", route) + "/?$")


def args_for(method, op):
    """Positional arguments get a value; required fields go as keywords too."""
    sig = inspect.signature(method)
    kwargs = {}
    for name, param in sig.parameters.items():
        if param.kind in (param.VAR_KEYWORD, param.VAR_POSITIONAL) or param.default is not param.empty:
            continue
        annotation = str(param.annotation)
        if "List" in annotation or name == "photos":
            kwargs[name] = ["https://example.com/a.jpg"]
        elif "Dict" in annotation:
            kwargs[name] = {}
        elif re.search(r"video|document|media_path", name):
            kwargs[name] = "https://example.com/a.mp4"
        elif name == "platforms":
            kwargs[name] = ["x"]
        else:
            kwargs[name] = f"v_{name}"
    for name, value in (("platforms", ["x"]), ("user", "v_user"), ("title", "t")):
        if name in sig.parameters and name not in kwargs:
            kwargs[name] = value
    takes_any = any(p.kind == p.VAR_KEYWORD for p in sig.parameters.values())
    if takes_any:
        for field in op["required"]:
            if re.fullmatch(r"[A-Za-z_]\w*", field) and field not in kwargs and field in op["route"]:
                kwargs[field] = f"v_{field}"
    return kwargs


def _response():
    response = MagicMock()
    response.status_code = 200
    response.content = b'{"success": true}'
    response.json.return_value = {"success": True}
    response.raise_for_status.return_value = None
    return response


class TestEveryOperationHasAMethod(unittest.TestCase):
    def test_nothing_is_left_without_a_method_or_a_reason(self):
        missing = [f'{o["id"]} ({o["verb"]} {o["route"]})' for o in OPS
                   if not method_for(o) and o["id"] not in MAP["excluded"]]
        self.assertEqual(missing, [], "Operations without a method; run python3 codegen/generate.py")

    def test_sdk_map_only_names_operations_of_the_spec(self):
        ids = {o["id"] for o in OPS}
        stale = [i for i in list(MAP["existing"]) + list(MAP["excluded"]) if i not in ids]
        self.assertEqual(stale, [])
        for op_id, why in MAP["excluded"].items():
            self.assertGreater(len(why), 20, f"{op_id} needs a reason")

    def test_generated_table_matches_the_spec(self):
        by_id = {o["id"]: o for o in OPS}
        for op_id, (verb, route, _meta) in TABLE.items():
            with self.subTest(op_id=op_id):
                self.assertIn(op_id, by_id, "generated method for an operation that left the spec")
                self.assertNotIn(op_id, MAP["existing"], "generated and hand-written")
                self.assertEqual(verb, by_id[op_id]["verb"])
                expected = MAP.get("overrides", {}).get(op_id, {}).get("path") or by_id[op_id]["route"]
                self.assertEqual(route, expected)

    def test_availability_notes_come_from_x_availability(self):
        with open(os.path.join(ROOT, "README.md"), encoding="utf-8") as fh:
            region = fh.read().split("<!-- openapi:availability -->")[1].split("<!-- /openapi:availability -->")[0]
        for route, item in SPEC["paths"].items():
            for verb in ("get", "post", "put", "patch", "delete"):
                op = item.get(verb)
                if not op:
                    continue
                na = op.get("x-availability") == "not_generally_available"
                with self.subTest(operation=op["operationId"]):
                    if op["operationId"] in TABLE:
                        self.assertEqual(bool(TABLE[op["operationId"]][2].get("na")), na)
                        doc = getattr(UploadPostClient, method_for({"id": op["operationId"]})).__doc__
                        self.assertEqual("Not generally available yet" in doc, na)
                    elif op["operationId"] in MAP["existing"]:
                        row = f'| `{MAP["existing"][op["operationId"]]}` | `{verb.upper()} /api{route}`'
                        self.assertEqual(row in region, na)

    def test_named_methods_exist(self):
        absent = [o["id"] for o in OPS if method_for(o) and not callable(getattr(UploadPostClient, method_for(o), None))]
        self.assertEqual(absent, [])

    def test_generated_code_is_up_to_date(self):
        result = subprocess.run([sys.executable, os.path.join(ROOT, "codegen", "generate.py"), "--check"],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)


class TestEachMethodSendsItsRequest(unittest.TestCase):
    def setUp(self):
        self.client = UploadPostClient("test-key")
        self.calls = []

        def record(verb):
            def call(url, *args, **kwargs):
                self.calls.append((verb, url))
                return _response()
            return call

        for verb in ("get", "post", "put", "patch", "delete"):
            patch.object(self.client.session, verb, side_effect=record(verb.upper())).start()
        patch.object(self.client.session, "request",
                     side_effect=lambda verb, url, **kw: record(verb.upper())(url)).start()
        self.addCleanup(patch.stopall)

    def test_every_operation(self):
        for op in OPS:
            name = method_for(op)
            if not name:
                continue
            with self.subTest(operation=op["id"], method=name):
                self.calls.clear()
                method = getattr(self.client, name)
                method(**args_for(method, op))
                self.assertTrue(self.calls, f"{name} sent nothing")
                regex = route_regex(op["route"])
                hit = any(verb == op["verb"] and regex.match(url.replace(BASE, "").split("?")[0])
                          for verb, url in self.calls)
                self.assertTrue(hit, f'{name} sent {self.calls}, not {op["verb"]} {op["route"]}')


class TestGeneratedMethods(unittest.TestCase):
    def setUp(self):
        self.client = UploadPostClient("test-key")
        self.request = patch.object(self.client.session, "request", return_value=_response()).start()
        self.addCleanup(patch.stopall)

    def sent(self):
        args, kwargs = self.request.call_args
        return args[0], args[1].replace(BASE, ""), kwargs

    def test_bearer_operation_sends_the_profile_jwt(self):
        self.client.list_client_post_approvals("profile-jwt")
        _, path, kwargs = self.sent()
        self.assertEqual(path, "/uploadposts/approvals/client")
        self.assertEqual(kwargs["headers"], {"Authorization": "Bearer profile-jwt"})

    def test_path_query_and_body_go_where_the_spec_says(self):
        self.client.test_webhook_subscription("whsub_1", event="upload_completed")
        verb, path, kwargs = self.sent()
        self.assertEqual((verb, path), ("POST", "/uploadposts/webhooks/subscriptions/whsub_1/test"))
        self.assertEqual(kwargs["json"], {"event": "upload_completed"})

        self.client.preview_chatgpt_ads_ad("ad 1", ad_account_id="acc", extra=True)
        verb, path, kwargs = self.sent()
        self.assertEqual(path, "/uploadposts/ads/chatgpt/ads/ad%201/preview")
        self.assertEqual(kwargs["params"], {"ad_account_id": "acc"})
        self.assertEqual(kwargs["json"], {"extra": True})

        self.client.list_team_audit(profile_username="p", limit=5, since=None)
        verb, path, kwargs = self.sent()
        self.assertEqual(kwargs["params"], {"profile_username": "p", "limit": 5})
        self.assertNotIn("json", kwargs)

    def test_create_webhook_subscription(self):
        self.client.create_webhook_subscription("https://example.com/hook", ["upload_completed"], source="n8n")
        verb, path, kwargs = self.sent()
        self.assertEqual((verb, path), ("POST", "/uploadposts/webhooks/subscriptions"))
        self.assertEqual(kwargs["json"], {"url": "https://example.com/hook", "events": ["upload_completed"], "source": "n8n"})

    def test_missing_path_parameter_fails_before_any_request(self):
        with self.assertRaises(UploadPostError):
            self.client.get_webhook_subscription("")
        self.request.assert_not_called()

    def test_file_download_returns_bytes(self):
        self.request.return_value.content = b"\x00\x01"
        self.assertEqual(self.client.download_ffmpeg_result("job"), b"\x00\x01")

    def test_local_file_turns_the_body_into_multipart(self):
        with tempfile.NamedTemporaryFile(suffix=".mp4") as fh:
            fh.write(b"x")
            fh.flush()
            self.client.create_ffmpeg_job("ffmpeg -i {input} {output}", "mp4", file=fh.name)
        _, _, kwargs = self.sent()
        self.assertEqual([k for k, _ in kwargs["files"]], ["file"])
        self.assertIn(("full_command", "ffmpeg -i {input} {output}"), kwargs["data"])

    def test_error_keeps_the_codes(self):
        response = MagicMock()
        response.status_code = 503
        response.json.return_value = {"success": False, "reason": "webhook_subscriptions_disabled"}
        response.headers = {}
        response.raise_for_status.side_effect = requests.exceptions.HTTPError("503", response=response)
        self.request.return_value = response
        with self.assertRaises(UploadPostError) as ctx:
            self.client.list_webhook_subscriptions()
        self.assertEqual(ctx.exception.status_code, 503)
        self.assertEqual(ctx.exception.error_code, "webhook_subscriptions_disabled")


class TestFixedMethods(unittest.TestCase):
    def test_validate_jwt_is_a_get_with_the_bearer_token(self):
        client = UploadPostClient("test-key")
        with patch.object(client.session, "get", return_value=_response()) as get:
            client.validate_jwt("profile-jwt")
        self.assertEqual(get.call_args[0][0], BASE + "/uploadposts/users/validate-jwt")
        self.assertEqual(get.call_args[1]["headers"], {"Authorization": "Bearer profile-jwt"})


